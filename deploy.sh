#!/bin/bash
set -e  # Прерываем выполнение скрипта при возникновении ошибки

# ----------------------------
# Настройки деплоя – измените под ваш проект
# ----------------------------
REPO_URL="https://github.com/username/repository.git"  # URL вашего репозитория
PROJECT_DIR="/opt/telegram-bot"                        # Путь, куда клонируется/обновляется проект
BRANCH="main"                                          # Ветка для деплоя
SERVICE_NAME="telegram-bot.service"                    # Имя systemd-сервиса, если используется

# ----------------------------
# Клонирование/обновление репозитория
# ----------------------------
if [ ! -d "$PROJECT_DIR" ]; then
    echo "Папка проекта не найдена. Клонируем репозиторий..."
    git clone -b "$BRANCH" "$REPO_URL" "$PROJECT_DIR"
else
    echo "Папка проекта существует. Обновляем репозиторий..."
    cd "$PROJECT_DIR"
    git pull origin "$BRANCH"
fi

cd "$PROJECT_DIR"

# ----------------------------
# Создание виртуального окружения, если отсутствует
# ----------------------------
if [ ! -d "venv" ]; then
    echo "Создаем виртуальное окружение..."
    python3 -m venv venv
fi

# Активируем виртуальное окружение и устанавливаем зависимости
source venv/bin/activate
pip install --upgrade pip
pip install -r requirements.txt

# ----------------------------
# Инициализация базы данных (если требуется)
# ----------------------------
echo "Инициализируем базу данных..."
python -c "from bot.db import init_db; init_db()"

# ----------------------------
# Перезапуск сервиса (предполагается, что вы настроили systemd-сервис)
# ----------------------------
echo "Перезапускаем systemd-сервис '$SERVICE_NAME'..."
sudo systemctl restart "$SERVICE_NAME"

echo "Деплой завершен успешно."
